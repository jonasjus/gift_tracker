// Writes web/config.js from environment variables during the Vercel build.
// Accepts the names Vercel's Supabase integration sets (NEXT_PUBLIC_*) as well as plain ones.
// Run locally with the variables set to generate the same file; without them it leaves config.js alone.
import { writeFileSync } from "node:fs";

const url = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
const anonKey = process.env.SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

if (!url || !anonKey) {
  if (process.env.VERCEL) {
    console.error("Missing SUPABASE_URL and/or SUPABASE_ANON_KEY. Add them under Project Settings → Environment Variables in Vercel, then redeploy.");
    process.exit(1);
  }
  console.log("SUPABASE_URL / SUPABASE_ANON_KEY not set; keeping the existing web/config.js.");
  process.exit(0);
}

const config = `// Generated by scripts/write-config.mjs at build time.
window.GIFT_CONFIG = ${JSON.stringify({ supabaseUrl: url, supabaseAnonKey: anonKey }, null, 2)};
`;
writeFileSync(new URL("../web/config.js", import.meta.url), config);
console.log(`Wrote web/config.js for ${url}`);
